// Regenerates lib/psl_data.js from the official list.  Usage: node tools/build_psl.mjs [path/to/public_suffix_list.dat]
// Without an argument it downloads https://publicsuffix.org/list/public_suffix_list.dat
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parsePsl } from "./psl_parse.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
const text = src ? fs.readFileSync(src, "utf8")
  : await (await fetch("https://publicsuffix.org/list/public_suffix_list.dat")).text();
const d = parsePsl(text);
if (d.icann.length < 1000 || d.private.length < 500) throw new Error("PSL looks truncated; refusing to write");
const out = `// Generated by tools/build_psl.mjs from the Public Suffix List (https://publicsuffix.org/), licensed MPL-2.0.
// Do not edit by hand. Regenerate: node tools/build_psl.mjs
export const PSL_GENERATED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const ICANN = ${JSON.stringify(d.icann)};
export const PRIVATE = ${JSON.stringify(d.private)};
export const WILD_ICANN = ${JSON.stringify(d.wildIcann)};
export const WILD_PRIVATE = ${JSON.stringify(d.wildPrivate)};
export const EXCEPTIONS = ${JSON.stringify(d.exceptions)};
`;
fs.writeFileSync(path.join(here, "..", "lib", "psl_data.js"), out);
console.log(`icann ${d.icann.length}, private ${d.private.length}, wildcards ${d.wildIcann.length + d.wildPrivate.length}, exceptions ${d.exceptions.length}`);
